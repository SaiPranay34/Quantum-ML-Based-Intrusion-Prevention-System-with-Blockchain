def add_noise(template):
    row = np.array(template, dtype=float)
    noise = np.array([np.random.uniform(-s, s) for s in NOISE_SCALE])
    row = row + noise
    row = np.clip(row, 0, None)
    return row

def generate_rows(templates, n):
    rows = []
    for _ in range(n):
        template = templates[np.random.randint(len(templates))]
        rows.append(add_noise(template))
    return np.array(rows)

def create_csv(filepath, n_total, attack_ratio):
    n_attack = int(n_total * attack_ratio)
    n_normal = n_total - n_attack

    attack_data = generate_rows(ATTACK_TEMPLATES, n_attack)
    normal_data = generate_rows(BENIGN_TEMPLATES, n_normal)

    attack_labels = np.ones(n_attack)
    normal_labels = np.zeros(n_normal)

    all_data = np.vstack([attack_data, normal_data])
    all_labels = np.concatenate([attack_labels, normal_labels])

    idx = np.random.permutation(n_total)
    all_data = all_data[idx]
    all_labels = all_labels[idx]

    df = pd.DataFrame(all_data, columns=FEATURE_COLUMNS)
    df["label"] = all_labels.astype(int)
    df.to_csv(filepath, index=False)

def main():
    os.makedirs(SIMULATION_DIR, exist_ok=True)
    os.makedirs(UPLOAD_DIR, exist_ok=True)

    simulation_configs = [0.2, 0.4, 0.5, 0.6, 0.8]
    for i, ratio in enumerate(simulation_configs, 1):
        path = os.path.join(SIMULATION_DIR, f"sim_{i}.csv")
        create_csv(path, 100, ratio)
        print(f"Created {path}")

    upload_configs = [0.1, 0.3, 0.5, 0.7, 0.9]
    for i, ratio in enumerate(upload_configs, 1):
        path = os.path.join(UPLOAD_DIR, f"sample_{i}.csv")
        create_csv(path, 200, ratio)
        print(f"Created {path}")

    print("All datasets created successfully")

if __name__ == "__main__":
    main()